const DICTS: Record<Locale, Dict> = { pt, en, es, fr, de, it, pl };

const STORAGE_KEY = "mshop.locale.v1";

type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
  price: (value: number, currency?: string) => string;
};

const I18nContext = createContext<Ctx | null>(null);

function detect(): Locale {
  if (typeof window === "undefined") return "pt";
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (saved && LOCALES.includes(saved)) return saved;
  } catch {
    /* ignore */
  }
  const nav = window.navigator.language?.slice(0, 2).toLowerCase() as Locale;
  return LOCALES.includes(nav) ? nav : "pt";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt");

  useEffect(() => {
    setLocaleState(detect());
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<Ctx>(() => {
    const dict = DICTS[locale];
    return {
      locale,
      setLocale,
      t: (key: string) => dict[key] ?? pt[key] ?? key,
      price: (value: number, currency = "EUR") =>
        new Intl.NumberFormat(LOCALE_META[locale].intl, { style: "currency", currency }).format(value),
    };
  }, [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
